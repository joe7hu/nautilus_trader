//! Shared formatting and CRC32 for Kraken Spot book checksums.

/// Formats a decimal string per Kraken book checksum rules.
///
/// Removes the decimal point then strips leading zeros, so `"0.12730000"` → `"12730000"`
/// and `"79754.0"` → `"797540"`.
pub(super) fn format_raw(raw: &str) -> String {
    let no_dot = raw.replace('.', "");
    let trimmed = no_dot.trim_start_matches('0');
    if trimmed.is_empty() {
        "0".to_string()
    } else {
        trimmed.to_string()
    }
}

/// IEEE CRC32 polynomial (reflected), inline to avoid adding a new dependency.
pub(super) fn crc32_ieee(data: &[u8]) -> u32 {
    let mut crc: u32 = 0xFFFF_FFFF;
    for &byte in data {
        crc ^= u32::from(byte);
        for _ in 0..8 {
            if crc & 1 != 0 {
                crc = (crc >> 1) ^ 0xEDB8_8320;
            } else {
                crc >>= 1;
            }
        }
    }
    !crc
}
